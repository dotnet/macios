	/// <summary>Sends text to a client and queries its text and selection.</summary>
	[NoiOS, NoTV, NoMacCatalyst]
	[Protocol (BackwardsCompatibleCodeGeneration = false), Model]
	[BaseType (typeof (NSObject))]
	interface IMKTextInput {
		/// <summary>Inserts converted text into the client document.</summary>
		/// <param name="text">A string or attributed string.</param>
		/// <param name="replacementRange">The document range to replace, or a range containing <see cref="NSRange.NotFound" /> to use the selection.</param>
		[Abstract]
		[Export ("insertText:replacementRange:")]
		void InsertText (NSObject text, NSRange replacementRange);

		/// <summary>Replaces text and marks it as an active composition.</summary>
		/// <param name="text">A string or attributed string.</param>
		/// <param name="selectionRange">The selection within the marked text.</param>
		/// <param name="replacementRange">The document range to replace.</param>
		[Abstract]
		[Export ("setMarkedText:selectionRange:replacementRange:")]
		void SetMarkedText (NSObject text, NSRange selectionRange, NSRange replacementRange);

		/// <summary>Gets the client's selected document range.</summary>
		[Abstract]
		[Export ("selectedRange")]
		NSRange SelectedRange { get; }

		/// <summary>Gets the document range occupied by marked text.</summary>
		[Abstract]
		[Export ("markedRange")]
		NSRange MarkedRange { get; }

		/// <summary>Gets attributed text from the client document.</summary>
		/// <param name="range">The document range.</param>
		/// <returns>The attributed text, or <see langword="null" /> if unavailable.</returns>
		[Abstract]
		[Export ("attributedSubstringFromRange:")]
		[return: NullAllowed]
		NSAttributedString GetAttributedSubstring (NSRange range);

		/// <summary>Gets the document length, or <see cref="NSRange.NotFound" /> if unavailable.</summary>
		[Abstract]
		[Export ("length")]
		nint Length { get; }

		/// <summary>Maps a screen position to a character index.</summary>
		/// <param name="point">The screen position.</param>
		/// <param name="mappingMode">The mapping mode.</param>
		/// <param name="inMarkedRange">Whether the position is in marked text.</param>
		/// <returns>The character index, or <see cref="NSRange.NotFound" /> if outside the text.</returns>
		[Abstract]
		[Export ("characterIndexForPoint:tracking:inMarkedRange:")]
		nint GetCharacterIndex (CGPoint point, IMKLocationToOffsetMappingMode mappingMode, out bool inMarkedRange);

		/// <summary>Gets text attributes and the line-height rectangle at a character index.</summary>
		/// <param name="index">The character index relative to the inline session.</param>
		/// <param name="lineRectangle">The line-height rectangle.</param>
		/// <returns>The text attributes.</returns>
		[Abstract]
		[Export ("attributesForCharacterIndex:lineHeightRectangle:")]
		NSDictionary GetAttributes (nuint index, out CGRect lineRectangle);

		/// <summary>Gets the attribute names supported for marked text.</summary>
		[Abstract]
		[Export ("validAttributesForMarkedText")]
		string [] ValidAttributesForMarkedText { get; }

		/// <summary>Overrides the keyboard layout used by the client.</summary>
		/// <param name="keyboardUniqueName">The unique keyboard layout name.</param>
		[Abstract]
		[Export ("overrideKeyboardWithKeyboardNamed:")]
		void OverrideKeyboard (string keyboardUniqueName);

		/// <summary>Selects an input mode.</summary>
		/// <param name="modeIdentifier">The input mode's identifier.</param>
		[Abstract]
		[Export ("selectInputMode:")]
		void SelectInputMode (string modeIdentifier);

		/// <summary>Gets whether the client supports Unicode text.</summary>
		[Abstract]
		[Export ("supportsUnicode")]
		bool SupportsUnicode { get; }

		/// <summary>Gets the client's bundle identifier.</summary>
		[Abstract]
		[Export ("bundleIdentifier")]
		string BundleIdentifier { get; }

		/// <summary>Gets the client's window level.</summary>
		[Abstract]
		[Export ("windowLevel")]
		int WindowLevel { get; }

		/// <summary>Determines whether the client supports a Text Services Manager property.</summary>
		/// <param name="property">The property tag.</param>
		/// <returns>Whether the property is supported.</returns>
		[Abstract]
		[Export ("supportsProperty:")]
		bool SupportsProperty (uint property);

		/// <summary>Gets a unique identifier for the input client.</summary>
		[Abstract]
		[Export ("uniqueClientIdentifierString")]
		string UniqueClientIdentifier { get; }

		/// <summary>Gets plain text from the client document.</summary>
		/// <param name="range">The requested document range.</param>
		/// <param name="actualRange">The actual range returned, which may differ to avoid splitting surrogate pairs.</param>
		/// <returns>The text, or <see langword="null" /> if unavailable.</returns>
		[Abstract]
		[Export ("stringFromRange:actualRange:")]
		[return: NullAllowed]
		string GetString (NSRange range, out NSRange actualRange);

		/// <summary>Gets the first screen rectangle corresponding to a text range.</summary>
		/// <param name="range">The document range.</param>
		/// <param name="actualRange">The text range covered by the rectangle.</param>
		/// <returns>The screen rectangle.</returns>
		[Abstract]
		[Export ("firstRectForCharacterRange:actualRange:")]
		CGRect GetFirstRect (NSRange range, out NSRange actualRange);
	}

