	/// <summary>Receives events and supplies composed text and conversion candidates.</summary>
	[NoiOS, NoTV, NoMacCatalyst]
	[Protocol (IsInformal = true, BackwardsCompatibleCodeGeneration = false), Model]
	[BaseType (typeof (NSObject))]
	interface IMKServerInput {
		/// <summary>Handles text, a virtual key code, and modifier flags.</summary>
		/// <param name="text">The text generated by the key event.</param>
		/// <param name="keyCode">The virtual key code.</param>
		/// <param name="modifiers">The event's modifier flags.</param>
		/// <param name="sender">The input client.</param>
		/// <returns>Whether the input was handled.</returns>
		[Export ("inputText:key:modifiers:client:")]
		bool InputText (string text, nint keyCode, NSEventModifierMask modifiers, NSObject sender);

		/// <summary>Handles text that did not match a key binding.</summary>
		/// <param name="text">The input text.</param>
		/// <param name="sender">The input client.</param>
		/// <returns>Whether the input was handled.</returns>
		[Export ("inputText:client:")]
		bool InputText (string text, NSObject sender);

		/// <summary>Handles an input event directly.</summary>
		/// <param name="inputEvent">The input event.</param>
		/// <param name="sender">The input client.</param>
		/// <returns>Whether the event was handled.</returns>
		[Export ("handleEvent:client:")]
		bool HandleEvent (NSEvent inputEvent, NSObject sender);

		/// <summary>Handles a command generated by a key binding.</summary>
		/// <param name="selector">The command selector.</param>
		/// <param name="sender">The input client.</param>
		/// <returns>Whether the command was handled.</returns>
		[Export ("didCommandBySelector:client:")]
		bool DidCommand (Selector selector, NSObject sender);

		/// <summary>Gets the current composition as a string or attributed string.</summary>
		/// <param name="sender">The input client.</param>
		/// <returns>The current composition, or <see langword="null" /> if there is none.</returns>
		[Export ("composedString:")]
		[return: NullAllowed]
		NSObject GetComposedString (NSObject sender);

		/// <summary>Gets the original text before conversion.</summary>
		/// <param name="sender">The input client.</param>
		/// <returns>The original text, or <see langword="null" /> if there is none.</returns>
		[Export ("originalString:")]
		[return: NullAllowed]
		NSAttributedString GetOriginalString (NSObject sender);

		/// <summary>Commits the current composition and ends the composition session.</summary>
		/// <param name="sender">The input client.</param>
		[Export ("commitComposition:")]
		void CommitComposition (NSObject sender);

		/// <summary>Gets possible conversions of the current composition.</summary>
		/// <param name="sender">The input client.</param>
		/// <returns>The candidate strings or attributed strings, or <see langword="null" /> if there are none.</returns>
		[Export ("candidates:")]
		[return: NullAllowed]
		NSObject [] GetCandidates (NSObject sender);
	}

