	/// <summary>Manages connections between an input method and its clients.</summary>
	[NoiOS, NoTV, NoMacCatalyst]
	[BaseType (typeof (NSObject))]
	[DisableDefaultCtor]
	interface IMKServer {
		/// <summary>Initializes a server using the controller and delegate classes specified in a bundle.</summary>
		/// <param name="name">The connection name registered by the server.</param>
		/// <param name="bundleIdentifier">The input method's bundle identifier.</param>
		[Export ("initWithName:bundleIdentifier:")]
		NativeHandle Constructor (string name, string bundleIdentifier);

		/// <summary>Initializes a server with explicit controller and delegate classes.</summary>
		/// <param name="name">The connection name registered by the server.</param>
		/// <param name="controllerClass">The input controller class.</param>
		/// <param name="delegateClass">The delegate class.</param>
		[Export ("initWithName:controllerClass:delegateClass:")]
		NativeHandle Constructor (string name, Class controllerClass, Class delegateClass);

		/// <summary>Gets the input method's bundle.</summary>
		[Export ("bundle")]
		NSBundle Bundle { get; }

		/// <summary>Notifies clients that a palette input method is terminating.</summary>
		/// <returns>Whether the palette can terminate safely.</returns>
		[Export ("paletteWillTerminate")]
		bool PaletteWillTerminate ();

		/// <summary>Gets whether the last key event was a dead key.</summary>
		[Export ("lastKeyEventWasDeadKey")]
		bool LastKeyEventWasDeadKey { get; }

		/// <summary>Gets the bundle key for the input method's modes dictionary.</summary>
		[Field ("IMKModeDictionary")]
		NSString ModeDictionary { get; }

		/// <summary>Gets the bundle key for the input controller class name.</summary>
		[Field ("IMKControllerClass")]
		NSString ControllerClass { get; }

		/// <summary>Gets the bundle key for the delegate class name.</summary>
		[Field ("IMKDelegateClass")]
		NSString DelegateClass { get; }
	}

