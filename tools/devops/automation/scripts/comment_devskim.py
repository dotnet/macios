import argparse
import json
import os
import re
from pathlib import Path
from urllib.parse import quote
from urllib.request import Request, urlopen


def comment_body(summary, gist_url, build_url, report_url=""):
    if not summary["has_failures"]:
        return None
    return (
        "### DevSkim source analysis failed\n\n"
        f'**{summary["banned_count"]} banned-API finding(s)** and '
        f'**{summary["error_count"]} scan error(s)** require attention.\n\n'
        f"[Detailed results (gist)]({gist_url}) | [Pipeline logs]({build_url})"
        + (f" | [HTML report on VSDrops]({report_url})" if report_url else "") + "\n\n"
        "The gist includes findings, file/line links, excerpts, and rule guidance. "
        "Findings are not proof of exploitable vulnerabilities.\n\n"
        "> [!NOTE]\n> This CI report comment was generated by GitHub Copilot automation.\n"
    )


def post_json(endpoint, data):
    request = Request(
        f"https://api.github.com/{endpoint}",
        data=json.dumps(data).encode("utf-8"),
        headers={"Authorization": f'Bearer {os.environ["GITHUB_TOKEN"]}',
                 "Content-Type": "application/json", "Accept": "application/vnd.github+json"},
        method="POST",
    )
    with urlopen(request, timeout=60) as response:
        return json.load(response)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Post DevSkim results in a gist and comment only when the check failed.")
    parser.add_argument("summary", type=Path)
    args = parser.parse_args(argv)
    summary = json.loads(args.summary.read_text(encoding="utf-8"))
    if not summary["has_failures"]:
        print("DevSkim passed; no gist or comment will be posted.")
        return 0
    repository = os.environ["BUILD_REPOSITORY_NAME"]
    if not re.fullmatch(r"[\w.-]+/[\w.-]+", repository):
        raise ValueError("Expected a GitHub repository")
    pr_number = os.environ.get("SYSTEM_PULLREQUEST_PULLREQUESTNUMBER", "")
    if os.environ.get("BUILD_REASON") == "PullRequest" or pr_number:
        if not re.fullmatch(r"[1-9][0-9]*", pr_number):
            raise ValueError("Expected a GitHub PR number")
        endpoint = f"repos/{repository}/issues/{pr_number}/comments"
    else:
        revision = os.environ["BUILD_SOURCEVERSION"]
        if not re.fullmatch(r"[a-fA-F0-9]{40}", revision):
            raise ValueError("Expected a Git commit SHA")
        endpoint = f"repos/{repository}/commits/{revision}/comments"
    title = repository.split("/")[1]
    build_number = quote(os.environ["BUILD_BUILDNUMBER"], safe="")
    build_id = quote(os.environ["BUILD_BUILDID"], safe="")
    attempt = quote(os.environ["SYSTEM_JOBATTEMPT"], safe="")
    report_url = (f"https://vsdrop.corp.microsoft.com/file/v1/{quote(title, safe='')}/devskim/"
                  f"{build_number}/{build_id}-{attempt}/;/index.html")
    build_url = (f'{os.environ["SYSTEM_COLLECTIONURI"]}{quote(os.environ["SYSTEM_TEAMPROJECT"], safe="")}'
                 f"/_build/results?buildId={build_id}")
    gist = post_json("gists", {
        "description": f"DevSkim results for {repository}, build {os.environ['BUILD_BUILDNUMBER']}",
        "public": False,
        "files": {"devskim-report.md": {
            "content": args.summary.with_name("report.md").read_text(encoding="utf-8"),
        }},
    })
    print(f'Published DevSkim results: {gist["html_url"]}')
    if os.environ.get("AGENT_JOBSTATUS") != "Succeeded":
        report_url = ""
    comment = post_json(endpoint, {"body": comment_body(summary, gist["html_url"], build_url, report_url)})
    print(f'Posted DevSkim report comment: {comment["html_url"]}')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
