	/// <summary>Controls an individual input session.</summary>
	[NoiOS, NoTV, NoMacCatalyst]
	[BaseType (typeof (NSObject))]
	[DisableDefaultCtor]
	interface IMKInputController : IMKServerInput, IMKStateSetting, IMKMouseHandling {
		/// <summary>Initializes a controller for a client session.</summary>
		/// <param name="server">The server managing the session.</param>
		/// <param name="delegateObject">The object handling callbacks, or <see langword="null" />.</param>
		/// <param name="inputClient">The client, which implements the text input protocol.</param>
		[Export ("initWithServer:delegate:client:")]
		NativeHandle Constructor (IMKServer server, [NullAllowed] NSObject delegateObject, NSObject inputClient);

		/// <summary>Sends the current composition to the client as marked text.</summary>
		[Export ("updateComposition")]
		void UpdateComposition ();

		/// <summary>Replaces the current composition with the original text.</summary>
		[Export ("cancelComposition")]
		void CancelComposition ();

		/// <summary>Gets additional attributes for a range of composed text.</summary>
		/// <param name="range">The range in the composition.</param>
		/// <returns>The composition attributes.</returns>
		[Export ("compositionAttributesAtRange:")]
		NSMutableDictionary GetCompositionAttributes (NSRange range);

		/// <summary>Gets the selection range within the marked text.</summary>
		[Export ("selectionRange")]
		NSRange SelectionRange { get; }

		/// <summary>Gets the range of client text to replace with marked text.</summary>
		[Export ("replacementRange")]
		NSRange ReplacementRange { get; }

		/// <summary>Gets attributes that mark a clause with a Text Services Manager highlight style.</summary>
		/// <param name="style">The Text Services Manager highlight style.</param>
		/// <param name="range">The range to mark.</param>
		/// <returns>The attributes for the clause.</returns>
		[Export ("markForStyle:atRange:")]
		NSDictionary GetMarkAttributes (nint style, NSRange range);

		/// <summary>Dispatches a command that is not part of text input, such as a menu action.</summary>
		/// <param name="selector">The action selector.</param>
		/// <param name="commandDictionary">The command's menu item and input client.</param>
		[Export ("doCommandBySelector:commandDictionary:")]
		void DoCommand (Selector selector, NSDictionary commandDictionary);

		/// <summary>Hides the input method's palettes.</summary>
		[Export ("hidePalettes")]
		void HidePalettes ();

		/// <summary>Gets the input method's command menu, or <see langword="null" /> if there is none.</summary>
		[NullAllowed]
		[Export ("menu")]
		NSMenu Menu { get; }

		/// <summary>Gets or sets the object that handles input controller callbacks.</summary>
		[NullAllowed]
		[Export ("delegate", ArgumentSemantic.Assign)]
		NSObject WeakDelegate { get; set; }

		/// <summary>Gets or sets the delegate for input and composition callbacks.</summary>
		[NullAllowed]
		[Wrap ("WeakDelegate")]
		IIMKServerInput Delegate { get; set; }

		/// <summary>Gets the server managing this session.</summary>
		[Export ("server")]
		IMKServer Server { get; }

		/// <summary>Gets the text input client.</summary>
		[Export ("client")]
		IIMKTextInput Client { get; }

		/// <summary>Notifies the controller that its session is about to close.</summary>
		[Export ("inputControllerWillClose")]
		void InputControllerWillClose ();

		/// <summary>Handles selection of a candidate annotation.</summary>
		/// <param name="annotation">The selected annotation.</param>
		/// <param name="candidate">The associated candidate.</param>
		[Export ("annotationSelected:forCandidate:")]
		void AnnotationSelected (NSAttributedString annotation, NSAttributedString candidate);

		/// <summary>Handles a change in the candidate selection.</summary>
		/// <param name="candidate">The newly highlighted candidate.</param>
		[Export ("candidateSelectionChanged:")]
		void CandidateSelectionChanged (NSAttributedString candidate);

		/// <summary>Handles the final selection of a candidate.</summary>
		/// <param name="candidate">The selected candidate.</param>
		[Export ("candidateSelected:")]
		void CandidateSelected (NSAttributedString candidate);

		/// <summary>Gets the command dictionary key for the selected menu item.</summary>
		[Field ("kIMKCommandMenuItemName")]
		NSString CommandMenuItemName { get; }

		/// <summary>Gets the command dictionary key for the input client.</summary>
		[Field ("kIMKCommandClientName")]
		NSString CommandClientName { get; }
	}

